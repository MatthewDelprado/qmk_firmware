#!/usr/bin/env python3
"""
gen_underglow.py — turn underglow.json into underglow_presets.h.

Run automatically by rules.mk on every build. Prints nothing on success; on a
problem it prints one line describing it, which rules.mk turns into a build error.
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "underglow.json")
OUT = os.path.join(HERE, "underglow_presets.h")

LED_COUNT = 17
LAYER_COUNT = 4
EFFECTS = {"solid": "FX_SOLID", "rainbow": "FX_RAINBOW", "spin": "FX_SPIN"}


class ConfigError(Exception):
    pass


def color(cfg, value, where):
    if isinstance(value, str):
        if value not in cfg["colors"]:
            raise ConfigError(f"{where}: unknown colour '{value}'")
        value = cfg["colors"][value]
    if not (isinstance(value, list) and len(value) == 2 and all(isinstance(v, int) and 0 <= v <= 255 for v in value)):
        raise ConfigError(f"{where}: colour must be a name or [hue, sat] in 0-255, got {value!r}")
    return value


def val(pct, where):
    if not (isinstance(pct, (int, float)) and 0 <= pct <= 100):
        raise ConfigError(f"{where}: brightness must be 0-100, got {pct!r}")
    return round(pct * 255 / 100)


def hsv(h_s, v):
    return f"{{{h_s[0]}, {h_s[1]}, {v}}}"


def layer_c(cfg, layer, where):
    effect = layer.get("effect")
    if effect not in EFFECTS:
        raise ConfigError(f"{where}: effect must be one of {', '.join(EFFECTS)}, got {effect!r}")
    v = val(layer.get("brightness", 100), where)
    a = b = [0, 0]
    period = 0
    if effect == "solid":
        a = b = color(cfg, layer.get("color"), where)
    elif effect == "spin":
        colors = layer.get("colors")
        if not (isinstance(colors, list) and len(colors) == 2):
            raise ConfigError(f"{where}: spin needs colors: [a, b]")
        a, b = color(cfg, colors[0], where), color(cfg, colors[1], where)
        period = layer.get("period_ms", 8000)
        if not (isinstance(period, int) and 100 <= period <= 65535):
            raise ConfigError(f"{where}: period_ms must be 100-65535")
    pulse = layer.get("pulse")
    if pulse:
        crest = hsv(color(cfg, pulse.get("color"), f"{where} pulse"), val(pulse.get("brightness", 100), f"{where} pulse"))
    else:
        crest = "{0, 0, 0}"
    return f"{{{EFFECTS[effect]}, {hsv(a, v)}, {hsv(b, v)}, {period}, {'true' if pulse else 'false'}, {crest}}}"


def generate(cfg):
    leds = cfg.get("led_positions")
    if not (isinstance(leds, list) and len(leds) == LED_COUNT):
        raise ConfigError(f"led_positions must list {LED_COUNT} [x, y] pairs")
    timing = cfg["pulse_timing"]
    presets = cfg["presets"]
    names = list(presets)
    if cfg.get("active") not in presets:
        raise ConfigError(f"active preset '{cfg.get('active')}' is not one of: {', '.join(names)}")

    lines = [
        "// Generated by gen_underglow.py from underglow.json. Do not edit; edit the JSON.",
        "#pragma once",
        "",
        f"#define PULSE_SPEED   {timing['speed']}",
        f"#define PULSE_WIDTH   {timing['width']}",
        f"#define PULSE_LIFE_MS {timing['life_ms']}",
        "",
        f"#define UNDERGLOW_ACTIVE_PRESET {names.index(cfg['active'])} /* {cfg['active']} */",
        "",
        "static const uint8_t led_pos_default[RGBLIGHT_LED_COUNT][2] = {",
        "    " + ", ".join(f"{{{x}, {y}}}" for x, y in leds) + ",",
        "};",
        "",
        "/* {effect, colour a, colour b, spin period ms, pulse?, pulse colour} per layer */",
        "static const underglow_preset_t underglow_presets[] = {",
    ]
    for name in names:
        layers = presets[name].get("layers", [])
        if len(layers) != LAYER_COUNT:
            raise ConfigError(f"preset '{name}' must define {LAYER_COUNT} layers")
        lines.append(f"    /* {name} */")
        lines.append("    {{")
        for i, layer in enumerate(layers):
            lines.append(f"        {layer_c(cfg, layer, f'{name} layer {i}')},")
        lines.append("    }},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    try:
        with open(SRC) as f:
            cfg = json.load(f)
        out = generate(cfg)
    except (OSError, json.JSONDecodeError, KeyError, ConfigError) as e:
        print(f"underglow.json: {e}")
        return 1
    try:
        with open(OUT) as f:
            if f.read() == out:
                return 0  # unchanged: keep the timestamp so make doesn't rebuild
    except OSError:
        pass
    with open(OUT, "w") as f:
        f.write(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
